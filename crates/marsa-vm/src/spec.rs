//! Describe a concrete VM independently of Apple framework configuration objects.

use std::{
    collections::HashSet,
    path::{Component, Path, PathBuf},
};

use marsa_core::{guest_boot::is_share_tag, settings::NetworkMode};

use crate::VmError;

/// An image attached to the guest as a block device.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DiskSpec {
    /// Absolute host path to the disk image.
    pub path: PathBuf,
    /// Whether the backend denies writes at the attachment.
    pub read_only: bool,
}

/// An allowlisted host directory exposed as a virtiofs share.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShareSpec {
    /// Stable tag used by the guest to mount the share.
    pub tag: String,
    /// Absolute host path approved by the share policy.
    pub host_path: PathBuf,
    /// Whether the virtualization backend denies writes from the guest.
    pub read_only: bool,
}

/// Selected guest network attachment.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NetworkSpec {
    /// Use the native host NAT attachment.
    Nat,
    /// Attach the user-space network stack.
    Userspace,
}

impl TryFrom<NetworkMode> for NetworkSpec {
    type Error = VmError;

    fn try_from(mode: NetworkMode) -> Result<Self, Self::Error> {
        match mode {
            NetworkMode::Nat => Ok(Self::Nat),
            NetworkMode::Userspace => Ok(Self::Userspace),
            NetworkMode::Auto => Err(invalid(
                "network",
                "resolve automatic network policy before creating a VM",
            )),
        }
    }
}

/// Resource and device configuration for a single Linux guest.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct VmSpec {
    /// Number of virtual CPUs.
    pub cpus: u32,
    /// Guest physical memory in bytes.
    pub memory_bytes: u64,
    /// Absolute path of the arm64 Linux boot kernel.
    pub kernel: PathBuf,
    /// Optional initial ramdisk image.
    pub initramfs: Option<PathBuf>,
    /// Linux kernel arguments generated by the host.
    pub cmdline: String,
    /// Immutable guest root disk.
    pub root_disk: DiskSpec,
    /// Separate persistent guest data disk.
    pub data_disk: DiskSpec,
    /// Directories allowed by the host share policy.
    pub shares: Vec<ShareSpec>,
    /// Selected network device attachment.
    pub network: NetworkSpec,
    /// Absolute host path for the guest serial transcript.
    pub console_log: PathBuf,
}

impl VmSpec {
    /// Check invariants shared by backends before platform-specific file and hardware validation.
    pub fn validate(&self) -> Result<(), VmError> {
        if self.cpus == 0 {
            return Err(invalid("cpus", "at least one virtual CPU is required"));
        }
        if self.memory_bytes == 0 {
            return Err(invalid("memory_bytes", "guest memory must be positive"));
        }
        if self.cmdline.contains('\0') {
            return Err(invalid("cmdline", "kernel arguments must be NUL-free"));
        }
        path("kernel", &self.kernel)?;
        if let Some(initramfs) = &self.initramfs {
            path("initramfs", initramfs)?;
        }
        path("root_disk", &self.root_disk.path)?;
        path("data_disk", &self.data_disk.path)?;
        path("console_log", &self.console_log)?;
        if !self.root_disk.read_only {
            return Err(invalid("root_disk", "the root disk must be read-only"));
        }
        if self.data_disk.read_only || self.data_disk.path == self.root_disk.path {
            return Err(invalid(
                "data_disk",
                "the data disk must be distinct and writable",
            ));
        }
        let disk_and_boot_paths = [
            Some(self.kernel.as_path()),
            self.initramfs.as_deref(),
            Some(self.root_disk.path.as_path()),
            Some(self.data_disk.path.as_path()),
        ];
        if disk_and_boot_paths
            .into_iter()
            .flatten()
            .any(|input| input == self.console_log)
        {
            return Err(invalid(
                "console_log",
                "the serial transcript needs a distinct path",
            ));
        }
        if self.data_disk.path == self.kernel
            || self.initramfs.as_ref() == Some(&self.data_disk.path)
        {
            return Err(invalid(
                "data_disk",
                "the writable disk needs a distinct boot path",
            ));
        }
        let mut tags = HashSet::new();
        for share in &self.shares {
            path("shares.host_path", &share.host_path)?;
            if !is_share_tag(&share.tag) || !tags.insert(share.tag.as_str()) {
                return Err(invalid("shares.tag", "share tags must be valid and unique"));
            }
        }
        Ok(())
    }
}

fn path(field: &'static str, value: &Path) -> Result<(), VmError> {
    if !value.is_absolute()
        || value.as_os_str().as_encoded_bytes().contains(&0)
        || value.components().any(|part| part == Component::ParentDir)
    {
        return Err(invalid(
            field,
            "an absolute, NUL-free path without parent traversal is required",
        ));
    }
    Ok(())
}

fn invalid(field: &'static str, reason: &'static str) -> VmError {
    VmError::InvalidSpec {
        field,
        reason: reason.into(),
    }
}
